//
// `cells` is the seed pattern: one character per cell, row-major, `w` wide by
// `h` tall, so cells.length === w * h.
//
//   encode: c = String.fromCharCode(40 + Math.round(v * 51))   // v in [0,1]
//   decode: v = (c.charCodeAt(0) - 40) / 51
//
// 52 levels spanning char codes 40..91 ('(' .. '['). That range contains no
// quote, backslash, backtick or dollar sign, so the payload needs no escaping
// in any JS/TS string literal. Max quantization error is 1/102 ~= 0.0098.
//
// `kn` (kernel core) and `gn` (growth function) are 0-BASED here; animals.json
// stores them 1-based. `b` is the beta peak list, decoded from the fraction
// string ("1/2,1" -> [0.5, 1]); its length is the number of kernel shells.

